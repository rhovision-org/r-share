#!/usr/bin/env python3
"""Generate or check the arm -> hazard -> finding -> improvement -> test matrix."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGISTERS = ROOT / "audit" / "registers"
OUT = ROOT / "audit" / "traceability"


def load(name: str) -> dict:
    return yaml.safe_load((REGISTERS / name).read_text())


def build() -> dict:
    arms = load("arms.yaml").get("arms", [])
    hazards = load("hazards.yaml").get("hazards", [])
    findings = load("findings.yaml").get("findings", [])
    improvements = load("improvements.yaml").get("improvements", [])
    tests = load("tests.yaml").get("tests", [])

    by_hazard = {h["id"]: h for h in hazards}
    by_finding = {f["id"]: f for f in findings}
    by_improvement = {r["id"]: r for r in improvements}
    by_test = {t["id"]: t for t in tests}

    rows = []
    for arm in arms:
        key = f'{arm["component"]}@"{arm["arm"]}"'
        arm_hazards = [h for h in hazards if h.get("arm") == key]
        hazard_ids = {h["id"] for h in arm_hazards}
        finding_ids = {f["id"] for f in findings
                       if hazard_ids.intersection(f.get("hazards", []))}
        improvement_ids = {r["id"] for r in improvements
                           if finding_ids.intersection(r.get("findings", []))
                           or hazard_ids.intersection(r.get("hazards", []))}
        test_ids = set()
        for hid in hazard_ids:
            test_ids.update(by_hazard[hid].get("tests", []))
        for fid in finding_ids:
            test_ids.update(by_finding[fid].get("tests", []) if "tests" in by_finding[fid] else [])
        for rid in improvement_ids:
            test_ids.update(by_improvement[rid].get("tests", []))
        rows.append({
            "component": arm["component"],
            "arm": arm["arm"],
            "source": arm.get("source"),
            "visibility": arm.get("visibility"),
            "flow_rule": arm.get("flow_rule"),
            "flow_status": arm.get("flow_status"),
            "lean_target": arm.get("lean_target"),
            "hazards": sorted(hazard_ids),
            "findings": sorted(finding_ids),
            "improvements": sorted(improvement_ids),
            "tests": sorted(test_ids),
        })

    covered = sum(1 for r in rows if r["flow_rule"])
    return {
        "schema": "rshare.traceability/v1",
        "summary": {
            "arms": len(rows),
            "arms_with_flow_rule": covered,
            "arms_with_hazard": sum(1 for r in rows if r["hazards"]),
            "hazards": len(hazards),
            "findings": len(findings),
            "improvements": len(improvements),
            "tests": len(tests),
        },
        "arms": rows,
    }


def render_markdown(matrix: dict) -> str:
    lines = [
        "# Traceability matrix",
        "",
        "Generated by `tools/audit_trace.py --write`; do not hand-edit.",
        "",
        "## Summary",
        "",
        "| Metric | Count |",
        "|---|---|",
    ]
    for key, value in matrix["summary"].items():
        lines.append(f"| {key} | {value} |")
    lines += [
        "",
        "## Arms",
        "",
        "| Component | Arm | Flow | Lean | Hazards | Findings | Improvements | Tests |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in matrix["arms"]:
        lines.append(
            f"| {row['component']} | `{row['arm']}` | {row['flow_rule'] or 'unmapped'} | "
            f"{row['lean_target'] or '-'} | "
            f"{', '.join(row['hazards']) or '-'} | "
            f"{', '.join(row['findings']) or '-'} | "
            f"{', '.join(row['improvements']) or '-'} | "
            f"{', '.join(row['tests']) or '-'} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()

    matrix = build()
    json_text = json.dumps(matrix, indent=2) + "\n"
    md_text = render_markdown(matrix)

    if args.write:
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / "matrix.json").write_text(json_text)
        (OUT / "matrix.md").write_text(md_text)
        print(f"audit-trace: wrote {len(matrix['arms'])} arms")
        return 0

    problems = []
    for name, expected in (("matrix.json", json_text), ("matrix.md", md_text)):
        path = OUT / name
        if not path.is_file():
            problems.append(f"missing {path}")
        elif path.read_text() != expected:
            problems.append(f"stale {path}; run tools/audit_trace.py --write")
    if problems:
        for problem in problems:
            print(f"audit-trace: {problem}", file=sys.stderr)
        return 1
    print(f"audit-trace: {len(matrix['arms'])} arms current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
